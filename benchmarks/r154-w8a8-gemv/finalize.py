import ast,hashlib,json,shutil,subprocess,tarfile,urllib.request
from pathlib import Path
P=Path(__file__).resolve().parent;repo=Path('/root/qwen-ascend');live=Path('/root/ascend-dev/fnx/fnx')
def run(args):
 r=subprocess.run(args,capture_output=True,text=True,timeout=25)
 return dict(code=r.returncode,stdout=r.stdout.strip(),stderr=r.stderr.strip())
def sha(f):return hashlib.sha256(f.read_bytes()).hexdigest()
before=json.load(open(P/'production-before-hashes.json'))
after={f.name:sha(f) for f in live.iterdir() if f.is_file() and f.suffix in ('.py','.so')}
health=json.load(urllib.request.urlopen('http://127.0.0.1:9002/health',timeout=8))
owned={f.name for f in P.glob('*.py') if any(t in f.name for t in ('probe','launch','sweep','calibrate','loader_check'))}
helpers=[];servers=[];workers=[];watchdogs=[]
for proc in Path('/proc').glob('[0-9]*'):
 try:
  args=proc.joinpath('cmdline').read_bytes().split(b'\0');decoded=[a.decode(errors='replace') for a in args if a]
  pid=int(proc.name)
  if b'fnx.server' in args:servers.append(pid)
  if b'fnx.pipeline_worker' in args:workers.append(pid)
  if any(Path(a).parent==P and Path(a).name in owned for a in decoded):helpers.append(dict(pid=pid,args=decoded))
  if decoded==['/bin/bash','/root/ascend-dev/watchdog.sh']:
   ppid=int(next(s.split()[1] for s in proc.joinpath('status').read_text().splitlines() if s.startswith('PPid:')))
   watchdogs.append(dict(pid=pid,ppid=ppid))
 except (OSError,ValueError):pass
manager=run(['systemctl','show','model-switch.service','-p','ActiveState','-p','RefuseManualStart','-p','DropInPaths'])
